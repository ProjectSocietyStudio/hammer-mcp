/** Fallback for anything undefined: a filled box, so a missing glyph is visible as one. */
const MISSING = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f];

export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
export const CELL_WIDTH = 6;
export const CELL_HEIGHT = 8;

/** Which pixels a string covers, at a scale, with the baseline at `y`. */
export function glyphPixels(
  text: string,
  x: number,
  y: number,
  scale: number,
): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  for (let i = 0; i < text.length; i++) {
    const rows = GLYPHS[text[i]!] ?? MISSING;
    const originX = x + i * CELL_WIDTH * scale;
    for (let row = 0; row < GLYPH_HEIGHT; row++) {
      const bits = rows[row]!;
      for (let col = 0; col < GLYPH_WIDTH; col++) {
        if ((bits & (1 << (GLYPH_WIDTH - 1 - col))) === 0) continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            out.push([
              Math.round(originX + col * scale + sx),
              Math.round(y - GLYPH_HEIGHT * scale + row * scale + sy),
            ]);
          }
        }
      }
    }
  }
  return out;
}

/** Width in pixels a string will occupy. */
export const textWidth = (text: string, scale: number): number =>
  text.length * CELL_WIDTH * scale;
