/**
 * A 5x7 bitmap font, so a raster plan can carry its own numbers.
 *
 * The perspective view deliberately has no text on it: the JSON beside it already carries the
 * camera, and a second copy in pixels is duplication. A plan is the opposite case. A room's
 * area written in the JSON and its outline drawn in the picture cannot be matched up by
 * looking, which is precisely what a plan is for -- the number has to be *on the thing*.
 *
 * Five by seven on a six by eight cell is the smallest legible size and the one every
 * terminal and old ROM used, for the same reason. Only the characters a plan writes are
 * defined: digits, a few letters, and the handful of symbols in "12: 34.5 m2".
 */

/** Each glyph is seven rows of five bits, high bit leftmost. */
